#!/usr/bin/env node
// Generates `apps/web/src/lib/api-types.ts` from the running API's
// /api/docs-json. This script boots the NestJS API in test mode in a child
// process, polls the OpenAPI document until ready, runs `openapi-typescript`,
// and shuts the API back down.
//
// Why a child-process boot rather than importing AppModule directly?
//   - The web workspace has no Nest deps, so importing AppModule pulls a huge
//     transitive graph into the SPA build.
//   - Booting the API the same way `npm run dev:api` does means the generated
//     spec matches what the SPA actually talks to.
//
// Usage:
//   node apps/web/scripts/generate-api-client.mjs                 # default port
//   API_DOCS_PORT=3010 node apps/web/scripts/generate-api-client.mjs
//
// In CI we expect the API to be already running; in that case set
// SKIP_BOOT=1 and OPENAPI_URL=http://host:port/api/v1/docs-json.

import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, '..', '..', '..');
const apiDir = resolve(repoRoot, 'apps', 'api');
const outFile = resolve(__dirname, '..', 'src', 'lib', 'api-types.ts');

const SKIP_BOOT = process.env.SKIP_BOOT === '1';
const explicitUrl = process.env.OPENAPI_URL;
const port = process.env.API_DOCS_PORT ?? '3010';
const url = explicitUrl ?? `http://127.0.0.1:${port}/api/docs-json`;

async function waitForReady(target, timeoutMs = 60_000) {
  const deadline = Date.now() + timeoutMs;
  let lastError;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(target);
      if (res.ok) return await res.json();
      lastError = new Error(`Got HTTP ${res.status}`);
    } catch (err) {
      lastError = err;
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw lastError ?? new Error('Timed out waiting for OpenAPI doc');
}

async function generate() {
  let child;
  if (!SKIP_BOOT) {
    child = spawn(
      process.platform === 'win32' ? 'npm.cmd' : 'npm',
      ['run', 'start:dev', '--', '--silent'],
      {
        cwd: apiDir,
        env: {
          ...process.env,
          PORT: port,
          NODE_ENV: 'development',
          // Avoid emitting interactive logs during codegen.
          API_LOG_LEVEL: process.env.API_LOG_LEVEL ?? 'warn',
        },
        stdio: 'inherit',
      },
    );
    child.on('exit', (code) => {
      if (code !== 0) process.exitCode = code ?? 1;
    });
  }

  const spec = await waitForReady(url).catch(async (err) => {
    if (child) child.kill();
    throw err;
  });

  const ast = await openapiTS(spec);
  const ts = astToString(ast);
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(
    outFile,
    `// Auto-generated by apps/web/scripts/generate-api-client.mjs.\n// Do not edit by hand — re-run \`npm run generate:api-types\` to refresh.\n\n${ts}`,
    'utf8',
  );

  if (child) {
    child.kill();
    // Give the child a beat to drain on Windows where SIGTERM is not real.
    await new Promise((r) => setTimeout(r, 300));
  }
}

generate().catch((err) => {
  console.error('[generate-api-client] failed:', err);
  process.exit(1);
});
